/** Canonical Phase 10 envelope. Payload is facts, never a mutable projection. */
export type LearningAuditEvent = Readonly<{
  eventId: string;
  eventType: LearningAuditEventType;
  workspaceId: string;
  occurredAt: string;
  actor: ProvenanceActor;
  correlationId: string;
  causationId?: string;
  schemaVersion: "10.0";
  references: LearningAuditReferences;
  payload: Readonly<Record<string, unknown>>;
}>;

export type LearningAuditEntry = Readonly<{
  sequence: number;
  previousHash: string | null;
  eventHash: string;
  event: LearningAuditEvent;
}>;

export interface LearningAuditLedger {
  append(event: LearningAuditEvent): Promise<LearningAuditEntry>;
  list(workspaceId: string): Promise<readonly LearningAuditEntry[]>;
  findByKnowledgeId(workspaceId: string, knowledgeId: string): Promise<readonly LearningAuditEntry[]>;
}

export type LearningAuditVerificationResult = Readonly<{
  workspaceId: string;
  status: "VALID" | "INVALID";
  verifiedEntryCount: number;
  violations: readonly string[];
  brokenAtSequence?: number;
  persistenceEffect: "NONE";
  authorityEffect: "UNCHANGED";
  executionPermissionGranted: false;
}>;

export interface LearningAuditLedgerVerifier {
  verify(workspaceId: string): Promise<LearningAuditVerificationResult>;
}
