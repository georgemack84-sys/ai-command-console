"use client";

import { useEffect, useState } from "react";

type Lesson = { id: string; position: number; objective: string; why_this_lesson: string; estimated_minutes: number; activity_type: string; next_step: string };
type Plan = { id: string; goal_summary: string; rationale: string; status: string; lessons: Lesson[] };

const apiOrigin = (process.env.NEXT_PUBLIC_LEARNING_API_ORIGIN ?? "").replace(/\/$/, "");
const api = (path: string) => `${apiOrigin}${path}`;
const localDemoEnabled = process.env.NODE_ENV !== "production";

async function request<T>(path: string, init?: RequestInit): Promise<T> {
  const response = await fetch(api(path), { ...init, credentials: "include" });
  const payload = await response.json() as { ok?: boolean; data?: T; error?: { message?: string } };
  if (!response.ok || !payload.ok || !payload.data) throw new Error(payload.error?.message ?? "Learning service request failed.");
  return payload.data;
}

export default function NoesisPage() {
  const [goal, setGoal] = useState("Diagnose systemd service failures");
  const [minutes, setMinutes] = useState("90");
  const [plan, setPlan] = useState<Plan | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [signingIn, setSigningIn] = useState(false);

  useEffect(() => { void request<{ plan: Plan | null }>("/api/learning/plans/current").then(({ plan }) => setPlan(plan)).catch(() => undefined); }, []);

  async function submit(event: React.FormEvent) {
    event.preventDefault();
    setBusy(true); setError(null); setNotice(null);
    try {
      const result = await request<{ plan: Plan }>("/api/learning/plans", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ goal: { free_text: goal }, constraints: { available_minutes_per_week: Number(minutes) || undefined } }),
      });
      setPlan(result.plan);
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Unable to create a plan."); } finally { setBusy(false); }
  }

  async function signInWithLocalDemo() {
    setSigningIn(true); setError(null); setNotice(null);
    try {
      const response = await fetch(api("/api/auth/dev-login"), { method: "POST", credentials: "include" });
      const payload = await response.json() as { ok?: boolean; error?: { message?: string } };
      if (!response.ok || !payload.ok) throw new Error(payload.error?.message ?? "Local demo sign-in failed.");
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Local demo sign-in failed."); } finally { setSigningIn(false); }
  }

  async function recordLessonEvent(lesson: Lesson, type: "STARTED" | "COMPLETED" | "SKIPPED") {
    if (!plan) return;
    setBusy(true); setError(null); setNotice(null);
    try {
      await request(`/api/learning/plans/${encodeURIComponent(plan.id)}/lessons/${encodeURIComponent(lesson.id)}/events`, {
        method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ type }),
      });
      setNotice(type === "COMPLETED" ? "Lesson completion recorded. Finish the targeted reassessment to add new evidence, then replan." : `Lesson marked ${type.toLowerCase()}.`);
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Unable to record lesson progress."); } finally { setBusy(false); }
  }

  async function replan() {
    if (!plan) return;
    setBusy(true); setError(null); setNotice(null);
    try {
      const result = await request<{ plan: Plan }>(`/api/learning/plans/${encodeURIComponent(plan.id)}/replan`, {
        method: "POST", headers: { "content-type": "application/json" },
        body: JSON.stringify({ goal: { free_text: goal }, constraints: { available_minutes_per_week: Number(minutes) || undefined } }),
      });
      setPlan(result.plan);
      setNotice("Plan recalculated. It will change when new assessment or approved evidence changes the learner state.");
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Unable to update the plan."); } finally { setBusy(false); }
  }

  return <main><p className="meta">Noesis · connected curriculum planner</p><h1>Your learning plan</h1><p>Plans are generated by Noesis using saved assessments, graph state, and learning history.</p><form onSubmit={submit}><label>Learning goal<input value={goal} onChange={(event) => setGoal(event.target.value)} required /></label><label>Minutes available each week<input value={minutes} onChange={(event) => setMinutes(event.target.value)} inputMode="numeric" /></label>{localDemoEnabled ? <button type="button" className="secondary" onClick={() => void signInWithLocalDemo()} disabled={signingIn || busy}>{signingIn ? "Signing in…" : "Use local demo account"}</button> : null}<button disabled={busy}>{busy ? "Generating…" : "Generate plan"}</button>{plan ? <button type="button" className="secondary" onClick={() => void replan()} disabled={busy}>Replan</button> : null}{error ? <p className="error">{error}</p> : null}{notice ? <p className="notice" role="status">{notice}</p> : null}</form>{plan ? <article><p className="meta">{plan.status}</p><h2>{plan.goal_summary}</h2><p>{plan.rationale}</p><ol>{plan.lessons.map((lesson) => <li key={lesson.id}><strong>{lesson.objective}</strong><p>{lesson.why_this_lesson}</p><p className="meta">{lesson.activity_type} · {lesson.estimated_minutes} min · Then: {lesson.next_step}</p>{lesson.activity_type !== "REASSESSMENT" ? <p className="actions"><button type="button" className="secondary" disabled={busy} onClick={() => void recordLessonEvent(lesson, "STARTED")}>Start</button><button type="button" className="secondary" disabled={busy} onClick={() => void recordLessonEvent(lesson, "COMPLETED")}>Complete</button><button type="button" className="secondary" disabled={busy} onClick={() => void recordLessonEvent(lesson, "SKIPPED")}>Skip</button></p> : null}</li>)}</ol></article> : null}</main>;
}
